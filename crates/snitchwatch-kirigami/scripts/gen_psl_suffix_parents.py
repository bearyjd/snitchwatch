#!/usr/bin/env python3
"""Generate data/psl-suffix-parents.txt from the rules file the `psl` crate embeds.

Dev-time only; offline. Usage (the psl crate source is in the cargo registry):

    scripts/gen_psl_suffix_parents.py \
        ~/.cargo/registry/src/*/psl-<version>/data/rules.txt <version> \
        > data/psl-suffix-parents.txt

A "suffix parent" is a domain of two or more labels that has at least one
public-suffix rule strictly beneath it (`amazonaws.com`, because
`s3.amazonaws.com` is a rule). A wildcard rule `*.x.y` also makes `x.y` a
parent. Exception rules (`!www.ck`) are not suffixes and are skipped.
"""
import hashlib
import sys


def ascii_label(label: str) -> str:
    try:
        return label.encode("idna").decode("ascii")
    except UnicodeError:
        return label


def main(path: str, version: str) -> None:
    raw = open(path, "rb").read()
    parents = set()
    for line in raw.decode("utf-8").splitlines():
        rule = line.strip().lower()
        if not rule or rule.startswith("//") or rule.startswith("!"):
            continue
        wildcard = rule.startswith("*.")
        labels = [ascii_label(l) for l in rule.removeprefix("*.").split(".")]
        for i in range(1, len(labels)):
            if len(labels) - i >= 2:
                parents.add(".".join(labels[i:]))
        if wildcard and len(labels) >= 2:
            parents.add(".".join(labels))
    out = sys.stdout
    out.write("# Public Suffix List suffix parents: domains with a PSL rule beneath them.\n")
    out.write("# Generated by scripts/gen_psl_suffix_parents.py; do not edit.\n")
    out.write(f"# psl-crate-version: {version}\n")
    out.write(f"# source: psl-{version}/data/rules.txt sha256:{hashlib.sha256(raw).hexdigest()}\n")
    for p in sorted(parents):
        out.write(p + "\n")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2])
